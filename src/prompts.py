"""
Module: prompts.py
Generates LLM text completions using HuggingFace Transformers pipelines.
"""

from typing import Optional
import torch
from transformers import AutoModelForCausalLM, AutoTokenizer


def generate_completion(
    prompt: str,
    model_name: str = "gpt2",
    max_length: int = 60,
    temperature: float = 0.7,
    top_p: float = 0.9,
    device: Optional[str] = None,
) -> str:
    """
    Generate causal language model completion for a given prompt string.

    Args:
        prompt: Input text prompt.
        model_name: HuggingFace model identifier. Defaults to 'gpt2'.
        max_length: Maximum token length of generated output.
        temperature: Sampling temperature (lower = more deterministic).
        top_p: Nucleus sampling probability threshold.
        device: 'cuda', 'mps' or 'cpu'. Auto-detected if None.

    Returns:
        Decoded output string generated by the language model.
    """
    if device is None:
        device = "cuda" if torch.cuda.is_available() else "cpu"

    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForCausalLM.from_pretrained(model_name).to(device)

    # Ensure pad token is configured
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    inputs = tokenizer(prompt, return_tensors="pt").to(device)

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_length=max_length,
            temperature=temperature,
            top_p=top_p,
            do_sample=True,
            pad_token_id=tokenizer.pad_token_id,
        )

    return tokenizer.decode(outputs[0], skip_special_tokens=True)